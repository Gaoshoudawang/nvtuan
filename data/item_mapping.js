// 获取道具图片的统一函数
window.getItemImage = function(itemName, type) {
  // 处理合并后的钻石（钻石×总数）
  if(itemName && itemName.indexOf('钻石×') === 0) {
    return 'images/items_box/钻石666/small.png';
  }
  if(type === 'small') {
    return window.ITEM_SMALL_IMAGES[itemName] || 'images/items_box/default/small.png';
  } else if(type === 'showcase') {
    return window.SHOWCASE_IMAGES[itemName] || null;
  }
  return window.ITEM_SMALL_IMAGES[itemName] || 'images/items_box/default/small.png';
};

// 获取道具品质
window.getItemQuality = function(itemName) {
  // 紫色品质：钻石和兑换币
  if(itemName.indexOf('钻石') === 0 || itemName.indexOf('HeartShot兑换币') === 0) {
    return 'purple';
  }
  return 'gold';
};

// 获取道具行为配置
window.getItemBehavior = function(itemName) {
  return window.ITEM_BEHAVIOR[itemName] || window.ITEM_BEHAVIOR['default'];
};

